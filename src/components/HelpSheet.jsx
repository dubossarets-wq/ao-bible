export default function HelpSheet({ pane, onClose }) {
  const { openSheet } = useApp();
  const [open, setOpen] = useState(null);
  const [q, setQ] = useState('');
  const topic = TOPICS.find((t) => t.id === open);
  const list = useMemo(() => {
    const s = q.trim().toLowerCase();
    return s ? TOPICS.filter((t) => (t.title + ' ' + t.steps.join(' ')).toLowerCase().includes(s)) : TOPICS;
  }, [q]);
  const groups = [...new Set(list.map((t) => t.group))];

  return (
    <BottomSheet title={topic ? topic.title : 'Инструкция'} onClose={onClose} onBack={topic ? () => setOpen(null) : null} initial={2}>
      {topic ? (
        <div className="help-topic">
          <ol className="help-steps">
            {topic.steps.map((s, i) => (
              <li key={i}>{s}</li>
            ))}
          </ol>
          {topic.action && (
            <button className="btn primary help-go" onClick={() => openSheet(topic.action[1], pane)}>
              {topic.action[0]} <ChevronRight size={17} />
            </button>
          )}
        </div>
      ) : (
        <>
          <div className="input-wrap">
            <input value={q} onChange={(e) => setQ(e.target.value)} placeholder="Что вы хотите сделать? Например: проповедь" aria-label="Поиск по инструкции" autoComplete="off" />
          </div>
          {groups.map((g) => (
            <section key={g} className="nav-group">
              <h4>{g}</h4>
              <div className="pref-list-main">
                {list
                  .filter((t) => t.group === g)
                  .map((t) => (
                    <button key={t.id} className="pref-row" onClick={() => setOpen(t.id)}>
                      <t.icon size={19} />
                      <span className="pref-row-text">{t.title}</span>
                      <ChevronRight size={17} className="pref-chev" />
                    </button>
                  ))}
              </div>
            </section>
          ))}
          {!list.length && <p className="pref-note">Ничего не нашлось. Попробуйте другое слово.</p>}
        </>
      )}
    </BottomSheet>
  );
}
