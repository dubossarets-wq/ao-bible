const KEY = 'newsSeen';

// Что показать при запуске: записи новее просмотренной. Первый запуск приложения — ничего (человеку всё ново).
export function pendingNews() {
  const seen = load(KEY, null);
  if (seen == null) {
    // Уже пользовался приложением (есть его данные), но «Что нового» ещё не видел — покажем последнюю запись
    let used = false;
    try {
      used = ['panes', 'settings', 'bookmarks', 'notes'].some((k) => localStorage.getItem(P + k) != null);
    } catch {
      /* хранилище недоступно */
    }
    if (!used) {
      markNewsSeen();
      return [];
    }
    return NEWS.slice(0, 1);
  }
  return NEWS.filter((n) => n.id > seen);
}

export const markNewsSeen = () => save(KEY, NEWS[0]?.id || '');
